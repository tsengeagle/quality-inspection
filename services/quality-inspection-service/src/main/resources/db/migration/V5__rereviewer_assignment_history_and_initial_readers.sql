-- D-055 第 1 點：複審指派歷史。只能新增，不能修改或刪除；每次指派或改派複審醫師一筆，
-- 與案件的指派變更在同一個交易寫入。
create table rereviewer_assignment_history (
    history_id number(19,0) generated by default as identity,
    case_id varchar2(255 char) not null,
    rereviewer_id varchar2(255 char) not null,
    assigned_at timestamp not null,
    assigned_by varchar2(255 char) not null,
    assignment_kind varchar2(16 char) not null,
    constraint pk_rereviewer_assignment_history primary key (history_id),
    constraint ck_rereviewer_assignment_kind check (assignment_kind in ('ASSIGN', 'REASSIGN'))
);
create index ix_rereviewer_history_case on rereviewer_assignment_history (case_id, rereviewer_id);
create index ix_rereviewer_history_rereviewer on rereviewer_assignment_history (rereviewer_id);

-- D-055 第 5 點：初審讀取者。只增不改，同一人同一案一筆。
create table initial_review_reader (
    reader_record_id number(19,0) generated by default as identity,
    case_id varchar2(255 char) not null,
    reader_id varchar2(255 char) not null,
    read_at timestamp not null,
    constraint pk_initial_review_reader primary key (reader_record_id),
    constraint uk_initial_review_reader unique (case_id, reader_id)
);

-- D-055 第 2 點：複審指派歷史是否完整。這個 migration 之前已存在的案件沒有歷史，一律為不完整（0）；
-- 之後建立的案件由程式寫入 1。不得事後把 0 改為 1，也不得補造歷史紀錄。
-- 正式環境在導入前沒有資料（D-045），所以正式資料全部是完整的。
alter table review_case add rereviewer_history_complete number(1,0) default 0 not null;
